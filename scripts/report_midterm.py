"""Draft of the midterm written report (WR): every number is read from results/, none typed by hand (convention 9).

Input : results/*.csv written by the analysis scripts (Parts 1 to 3)
Output: results/report_midterm.md
No random operations.

The draft follows the WR outline in PROJECT.md: question, data, methods, results (Part 1, Part 2, the error-bar
study, Part 3), what it means, limitations and next steps. The team edits the wording; the numbers are regenerated
by rerunning this script after any analysis changes.
Run from the repository root after the analysis scripts: python scripts/report_midterm.py
"""
import sys, re, pathlib
import numpy as np, pandas as pd
sys.path.insert(0, "scripts")
import modeling as M

RES = pathlib.Path("results")
OUT = RES / "report_midterm.md"


def csv(name):
    return pd.read_csv(RES / f"{name}.csv")


def hyp(name, h, version=None):
    d = csv(f"{name}_hypotheses")
    d = d[d.hypothesis == h]
    if version is not None and "version" in d:
        d = d[d.version == version]
    return d.iloc[0]


def verdict(r):
    return "supported" if str(r.supported) == "True" else "not supported"


def main():
    ov = csv("eda_overall").set_index("metric").value
    met = csv("part2_models_metrics")
    met = met[(met.headline == True) & (met.target == "match")]
    ev = met[met.fold_scheme == "event"]
    rr = met[met.fold_scheme == "random-row"]
    get = lambda d, fs, m: d[(d.feature_set == fs) & (d.model == m)].iloc[0]
    pre, date = ev[ev.feature_set == "pre"], ev[ev.feature_set == "pre+date"]
    best_pre, best_date = pre.loc[pre.auc.idxmax()], date.loc[date.auc.idxmax()]
    lo_pre, lo_date = pre.loc[pre.auc.idxmin()], date.loc[date.auc.idxmin()]
    lg_pre, lg_date = get(ev, "pre", "logistic"), get(ev, "pre+date", "logistic")
    gap = (rr.set_index(["feature_set", "model"]).auc - ev.set_index(["feature_set", "model"]).auc).dropna()
    sv = csv("part1_models_stated_vs_revealed").set_index(["rater_gender", "attribute"])
    noise = csv("fold_seed_noise_summary").set_index("quantity")
    lr_noise = noise.loc["full logistic `pre` AUC over fold seeds"]
    rf_noise = noise.loc["random forest `pre` AUC over forest seeds (headline folds)"]
    p1_cc, p1_w12 = hyp("part1_models", "P1", "complete-case"), hyp("part1_additions", "P1", "without wave 12, headline folds")
    eb = csv("errorbars_real")
    ebx = lambda fs, se: eb[(eb.feature_set == fs) & (eb.model == "logistic") & (eb.scheme == "event") & (eb.se_type == se)].iloc[0]
    cov = csv("sim_cv_matched_coverage")
    cov = cov[cov.target.str.startswith("error on new events (this")].set_index("procedure")
    within = csv("yes_extensions_within_event").set_index("prediction")
    fc = csv("forecasts_metrics").set_index("rater_gender").loc["both"]
    rk = csv("ranking_variance").set_index("rater_gender")
    mr = csv("mean_reversion_summary").set_index(["rating", "direction"])
    sm = csv("stable_matching_summary").set_index("matching")
    srm = csv("srm_estimates").set_index("quantity")
    chk = csv("srm_check").set_index("quantity")
    designs = (RES / "sim_cv_designs_hypotheses.csv").exists()

    def iv(q):
        r = srm.loc[q]
        return f"{r.estimate:.3f} (90% interval {r.ci90_low:.3f} to {r.ci90_high:.3f})"

    T = []
    add = T.append
    add("# Predicting mutual interest before two strangers meet: midterm written report (draft)\n")
    add("Sophia Qin, Jenna Yang, Abraham Yeung. Math 195. Generated by `scripts/report_midterm.py` from `results/`; "
        "edit the wording, not the numbers.\n")
    add("## 1. Question\n")
    add("How well can we predict, from what is known before two strangers meet, whether both will want to see each other "
        "again? Which characteristics of the pair matter? And how much does a four-minute conversation add? A second "
        "question is statistical. The rows of this data share people and events, so the usual cross-validation error bars "
        "are too narrow; we measure by how much, and test which constructions are honest. Every hypothesis was committed "
        "to `PREREG.md` before its test ran.\n")
    add("## 2. Data\n")
    add(f"The Columbia speed-dating experiment (Fisman et al. 2006) has {int(ov['people'])} participants "
        f"({int(ov['women'])} women, {int(ov['men'])} men) at {int(ov['events'])} events. Within an event every woman met "
        f"every man for four minutes, and each said yes or no. Our unit for predicting a match is the woman-man pair: "
        f"{int(ov['dyads']):,} dyads, of which {ov['match rate (per dyad)']:.1%} were mutual yeses. Participants said yes to "
        f"{ov['yes rate, all']:.0%} of their dates (women {ov['yes rate, women']:.1%}, men {ov['yes rate, men']:.1%}). "
        f"Two feature sets are compared throughout. `pre` holds what is known before the date: each person's sign-up "
        f"answers, plus pair features such as the age gap, interest correlation, same field, same goal and preference "
        f"alignment. `pre+date` adds the ratings the two gave each other during the date.\n")
    add("## 3. Methods\n")
    add("Every model is evaluated by **event 5-fold cross-validation**: whole events are held out, so the people in a test "
        "fold are strangers to the model. Missing answers are filled with training-fold medians plus missing-value flags, "
        "and a complete-case version runs alongside. Classification uses the training folds' match rate as the threshold. "
        "We report AUC, balanced accuracy, sensitivity and specificity. Error bars are clustered by event, and each formula "
        "was checked on simulated data with the real design before being reported. The full procedure, with code, is in "
        "`results/methods_doc.pdf`.\n")
    add("## 4. Results\n")
    add("### 4.1 Part 1: a weak signal before the date, a strong one after\n")
    add(f"Before the date, the models' event-held-out AUCs run from {lo_pre.auc:.3f} ({lo_pre.model}) to {best_pre.auc:.3f} "
        f"({best_pre.model}, SE {best_pre.auc_se:.3f}). With the in-date ratings they run from {lo_date.auc:.3f} to "
        f"{best_date.auc:.3f} ({best_date.model}).\n")
    rows = ["| Model | `pre` AUC (SE) | `pre+date` AUC (SE) |", "| --- | --- | --- |"]
    for m in ["logistic", "stepwise_forward", "lda", "qda", "lasso", "tree", "bagging", "rf", "boosting", "ensemble_mean", "ensemble_stacked"]:
        a, b = get(ev, "pre", m), get(ev, "pre+date", m)
        rows.append(f"| {m.replace('_', ' ')} | {a.auc:.3f} ({a.auc_se:.3f}) | {b.auc:.3f} ({b.auc_se:.3f}) |")
    add("\n".join(rows) + "\n\nTable 1. Event 5-fold CV, headline specification, " + f"{int(ov['dyads']):,} dyads.\n")
    h = {k: hyp("part1_models", k, "headline") for k in ("P1", "P2", "P3", "P4")}
    add(f"- **P1** ({verdict(h['P1'])}): {h['P1'].statistic}. This pass is fragile. Re-drawing the folds moves the "
        f"logistic AUC with SD {lr_noise.sd:.3f}, forest seeds move the forest from {rf_noise['min']:.3f} to {rf_noise['max']:.3f}, "
        f"and P1 fails on complete cases ({p1_cc.statistic}) and without wave 12 ({p1_w12.statistic}).")
    add(f"- **P2** ({verdict(h['P2'])}): {h['P2'].statistic}.")
    add(f"- **P3** ({verdict(h['P3'])}): {h['P3'].statistic}. Pair compatibility adds almost nothing beyond the two "
        f"people's own answers, as Joel, Eastwick and Finkel (2017) found.")
    add(f"- **P4** ({verdict(h['P4'])}): {h['P4'].statistic}.")
    w, mn = sv.loc[("women", "attr")], sv.loc[("men", "attr")]
    add(f"- **P5** (supported): in the yes model, attractiveness carries {w.revealed_share:.0f}% of women's positive weight "
        f"against the {w.stated_share:.0f}% of their 100 points they gave it beforehand. For men the figures are "
        f"{mn.revealed_share:.0f}% against {mn.stated_share:.0f}%.\n")
    add("### 4.2 Part 2: no model breaks the ceiling\n")
    for name, k, v in [("part2_models", "T1", "headline, pre"), ("part2_models", "T2", "headline, pre"), ("part2_models", "E1", "headline, pre"),
                       ("part2_models", "E2", "headline, pre+date"), ("part2_models", "D1", "headline"), ("part2_models", "D2", "headline")]:
        r = hyp(name, k, v)
        add(f"- **{k}** ({verdict(r)}): {r.statistic}.")
    a1 = hyp("part2_models", "A1", "headline")
    add(f"- **A1** ({verdict(a1)}): random-row CV raised the AUC of every model by {gap.min():+.3f} to {gap.max():+.3f} "
        f"(logistic `pre`: {get(ev, 'pre', 'logistic').auc:.3f} to {get(rr, 'pre', 'logistic').auc:.3f}). The tree models "
        f"were not inflated more than logistic regression.")
    w1 = hyp("yes_extensions", "W1", "all decisions")
    add(f"- **W1** ({verdict(w1)}): {w1.statistic}. Once a model has seen the same people earlier that evening, a yes "
        f"is predictable; before the date it is not.")
    s1 = hyp("yes_extensions", "S1", "both genders")
    add(f"- **S1** ({verdict(s1)}): {s1.statistic}.")
    for k in ("B1", "B2"):
        r = csv("ranking_hypotheses").query("hypothesis == @k").iloc[0]
        add(f"- **{k}** ({verdict(r)}): {r.statistic}.")
    c1, c2 = hyp("forecasts", "C1"), hyp("forecasts", "C2")
    add(f"- **C1** ({verdict(c1)}): {c1.statistic}. People's guesses that their date would say yes averaged "
        f"{fc.mean_forecast:.2f} against a real rate of {fc.yes_rate:.2f}.")
    add(f"- **C2** ({verdict(c2)}): {c2.statistic}.\n")
    add("### 4.3 The error-bar study\n")
    nv, cr, tw = ebx("pre", "naive (independent rows)"), ebx("pre", "cluster-robust by event"), ebx("pre", "two-way cluster-robust (woman, man)")
    cn = ebx("pre", "cluster-nested, bias-adjusted (centre moved)")
    add(f"On the real data, the naive SE of the full logistic model's `pre` error rate is {nv.se:.4f}. Clustering by "
        f"event gives {cr.se:.4f} ({cr.se_ratio_to_naive:.1f} times), two-way clustering by woman and man gives {tw.se:.4f} "
        f"({tw.se_ratio_to_naive:.1f} times), and our cluster-nested, bias-adjusted interval gives {cn.se:.4f} "
        f"({cn.se_ratio_to_naive:.1f} times). In a simulation matched to the data (A2, {verdict(hyp('sim_cv_matched', 'A2'))}), "
        f"each 90% interval covered the true error on new events as follows:\n")
    rows = ["| Interval | Coverage | Mean half-width |", "| --- | --- | --- |"]
    for p, r in cov.iterrows():
        rows.append(f"| {p} | {r.coverage_90:.1%} | {r.mean_half_width:.4f} |")
    add("\n".join(rows) + "\n\nTable 2. 500 simulated data sets with the real design (`sim_cv_matched.py`).\n")
    add("The conventional interval and the published nested-CV interval of Bates, Hastie and Tibshirani (2024) both fall "
        "well short. Holding out events fixes what is being estimated. In this design the cluster-robust SE over-covers, and our "
        "cluster-nested, bias-adjusted version is closest to 90%. A literature check (`proposals/07`) found no paper that "
        "combines grouped folds at both levels, a cluster-robust outer variance and the bias adjustment, and tests its "
        "coverage. That combination is the candidate contribution, framed as an extension of Bates et al. to clustered data.\n")
    if designs:
        dh = csv("sim_cv_designs_hypotheses").set_index("hypothesis")
        dg = csv("sim_cv_designs_diagnostics")
        dg = dg[dg.design != "dyadic"].astype({"events": float})
        cv = csv("sim_cv_designs_coverage")
        ours = cv[(cv.procedure == "event cluster-nested, bias-adjusted") & ((cv.person_sd > 0) | (cv.event_sd > 0))]
        rng_ = lambda d: f"{d.coverage_90.min():.1%} to {d.coverage_90.max():.1%}"
        cr = cv[(cv.procedure == "event CV, cluster-robust SE") & ((cv.person_sd > 0) | (cv.event_sd > 0))]
        add(f"Across 18 simulated designs: **N1** ({verdict(dh.loc['N1'])}): {dh.loc['N1'].statistic}. "
            f"**N2** ({verdict(dh.loc['N2'])}): {dh.loc['N2'].statistic}. Our interval covers {rng_(ours[ours.events == 21])} with "
            f"the real 21 events, but {rng_(ours[ours.events == 10])} with 10 redrawn events and {rng_(ours[ours.events == 40])} with 40. "
            f"In {dg.share_zero_width.min():.0%} to {dg.share_zero_width.max():.0%} of data sets its MSE estimate is zero or "
            f"negative, which gives a zero-width interval; among the rest it covers "
            f"{dg.coverage_bias_adjusted_given_positive.min():.0%} to {dg.coverage_bias_adjusted_given_positive.max():.0%}. The "
            f"cluster-robust SE covers {rng_(cr[cr.events == 21])} with the real events but {rng_(cr[cr.events != 21])} with "
            f"redrawn ones, so the A2 figures are flattered by holding the events fixed. A post hoc repair, the larger of "
            f"the cluster-robust and cluster-nested SEs, covered {dg.coverage_floor_cr_cluster_nested.min():.0%} to "
            f"{dg.coverage_floor_cr_cluster_nested.max():.0%} in every design; it will be pre-registered before it is tested.\n")
    else:
        add("The design grid behind N1 and N2 is still running.\n")
    add("### 4.4 Part 3: luck, mutual liking and stable matches\n")
    r1, lk = hyp("mean_reversion", "R1"), mr.loc[("like", "odd to even")]
    add(f"- **R1** ({verdict(r1)}): {r1.statistic}. **R2** ({verdict(hyp('mean_reversion', 'R2'))}): empirical-Bayes shrinkage "
        f"cut the RMSE of predicting the other half from {lk.rmse_raw:.3f} to {lk.rmse_shrunk:.3f}. The evening's most-liked "
        f"person is partly lucky.")
    add(f"- **K1** ({verdict(hyp('srm', 'K1'))}): dyadic reciprocity of liking is {iv('dyadic_reciprocity')}. Liking splits into "
        f"the rater ({srm.loc['actor_share'].estimate:.0%}), the person rated ({srm.loc['partner_share'].estimate:.0%}) and "
        f"the pair plus noise ({srm.loc['residual_share'].estimate:.0%}).")
    add(f"- **K2** ({verdict(hyp('srm', 'K2'))}): generalized reciprocity is {iv('generalized_reciprocity')}. Our simulation "
        f"check found this registered estimator biased by {chk.loc['generalized_reciprocity'].bias:+.3f}. A corrected "
        f"estimator, which is exploratory, gives {iv('generalized_reciprocity_corrected')}.")
    m_, w_ = sm.loc["men propose"], sm.loc["women propose"]
    add(f"- **Stable matching** (exploratory): {m_.share_mutual_yes:.0%} of stable pairs were mutual yeses, and "
        f"{sm.loc['realized (mutual yeses)'].share_of_realized_in_a_stable_matching:.0%} of real matches were stable pairs. "
        f"The proposing side gets better-ranked partners: men {m_.men_mean_rank_of_partner:.2f} against women "
        f"{m_.women_mean_rank_of_partner:.2f} when men propose, and women {w_.women_mean_rank_of_partner:.2f} against men "
        f"{w_.men_mean_rank_of_partner:.2f} when women propose.\n")
    add("### 4.5 Part 4: race, reciprocity of yes decisions, and repairing the error bars\n")
    if (RES / "race_models_hypotheses.csv").exists():
        p3d = hyp("race_models", "P3d", "headline"); rates = csv("race_models_rates").set_index("rater_gender")
        yc = csv("race_models_yes"); sr = yc[yc.term == "samerace"].set_index("rater_gender")
        add(f"- **P3d** ({verdict(p3d)}; the team decided on 2026-10-15 to include race variables in this block only): {p3d.statistic}. "
            f"In the framing of Fisman et al. (2008), women said yes to {rates.loc['women'].yes_rate_same_race:.1%} of same-race dates and "
            f"{rates.loc['women'].yes_rate_different_race:.1%} of others (men {rates.loc['men'].yes_rate_same_race:.1%} and "
            f"{rates.loc['men'].yes_rate_different_race:.1%}); with the six ratings held fixed, the same-race coefficient is "
            f"{sr.loc['women'].coef:+.3f} (SE {sr.loc['women'].se_cluster_event:.3f}) for women and {sr.loc['men'].coef:+.3f} "
            f"(SE {sr.loc['men'].se_cluster_event:.3f}) for men.")
    if (RES / "srm_dec_hypotheses.csv").exists():
        k3 = hyp("srm_dec", "K3"); g = csv("srm_dec_estimates").set_index("quantity").loc["generalized_reciprocity"]
        add(f"- **K3** ({verdict(k3)}): {k3.statistic}. Exploratory: people who say yes often are chosen less often "
            f"(generalized reciprocity of the decisions {g.estimate:.3f}, 90% interval {g.ci90_low:.3f} to {g.ci90_high:.3f}).")
    if (RES / "sim_cv_repair_hypotheses.csv").exists():
        rh = csv("sim_cv_repair_hypotheses").set_index("hypothesis")
        for k in ("N3", "N4", "N5"):
            add(f"- **{k}** ({verdict(rh.loc[k])}): {rh.loc[k].statistic}.")
        rc = csv("sim_cv_repair_coverage")
        rc = rc[rc.design.str.startswith("grid") & ((rc.person_sd > 0) | (rc.event_sd > 0))]
        stat = lambda name: rc[rc.procedure == name]
        nb, fl = stat("Nadeau-Bengio corrected t, grouped folds"), stat("floor: max(cluster-robust, cluster-nested) (N3)")
        add(f"- Exploratory comparison: the Nadeau-Bengio corrected t on event folds covered {nb.coverage_90.min():.1%} to "
            f"{nb.coverage_90.max():.1%} over the same designs, with a mean half-width of {nb.mean_half_width.mean():.3f} against "
            f"{fl.mean_half_width.mean():.3f} for the floor. An existing correction, applied to whole events, does as well as our "
            f"repair; a confirmatory test is the next pre-registration.")
    add("")
    add("## 5. What it means\n")
    add("What is known before the date carries a small, real signal. It mostly reflects who tends to like others and who "
        "tends to be liked, not who suits whom, and no model choice gets past it. The four-minute meeting carries far more "
        "information than everything known beforehand. Standard error bars on such results are far too narrow when people "
        "and events repeat; holding out whole events and using event-aware error bars is necessary, not optional.\n")
    add("## 6. Limitations and next steps\n")
    add("- One experiment, 21 events, one city and one population; the P1 result sits within fold-to-fold noise.\n"
        "- Race variables are excluded until the team records a decision.\n"
        "- Next: the comparison intervals named by the literature check (Nadeau-Bengio, Bayle et al., cluster bootstrap, "
        "internal-external CV); why the cluster-robust SE over-covers; Jenna's review of the propositions in "
        "`proposals/06`.\n")
    OUT.write_text("\n".join(T))
    print(f"wrote {OUT} ({len(' '.join(T).split())} words)")


if __name__ == "__main__":
    main()
